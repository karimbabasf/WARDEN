#!/usr/bin/env node
// Generates the Ed25519 keypair that signs WARDEN licenses, and the conformance
// vectors that both the Node signer and the Rust verifier are tested against.
//
// The private seed is printed once and written to .env.local (gitignored). It is
// never committed. The public key IS committed, in two places that must agree:
// docs/license-pubkey.json and src-tauri/src/license/pubkey.rs.
//
// Run with --vectors-only to regenerate vectors from the existing .env.local key
// without minting a new identity (minting a new one invalidates every license
// already sold, so the default path refuses to overwrite).

import { generateKeyPairSync, createPrivateKey, createPublicKey, sign } from 'node:crypto'
import { readFileSync, writeFileSync, existsSync, appendFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

// Raw 32-byte Ed25519 keys are not a format node's KeyObject takes directly, so
// wrap them in the fixed DER prefixes. These byte strings are the ASN.1 headers
// for PKCS8 Ed25519 private and SPKI Ed25519 public respectively; both are
// constant because the algorithm and key length are constant.
const PKCS8_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex')
const SPKI_PREFIX = Buffer.from('302a300506032b6570032100', 'hex')

const seedToPrivate = (seed) =>
  createPrivateKey({ key: Buffer.concat([PKCS8_PREFIX, seed]), format: 'der', type: 'pkcs8' })

const privateToRawPublic = (priv) =>
  createPublicKey(priv).export({ format: 'der', type: 'spki' }).subarray(SPKI_PREFIX.length)

const b64u = (buf) => Buffer.from(buf).toString('base64url')

/** The canonical payload. Key order is part of the format: both sides serialize
 *  by hand rather than via JSON.stringify on an object literal, so that a future
 *  refactor cannot silently reorder and break every key in the wild. */
export const encodePayload = ({ v, id, email, seats, iat }) =>
  `{"v":${v},"id":${JSON.stringify(id)},"email":${JSON.stringify(email)},"seats":${seats},"iat":${iat}}`

export const mintKey = (seed, claims) => {
  const payload = Buffer.from(encodePayload(claims), 'utf8')
  const signature = sign(null, payload, seedToPrivate(seed))
  return `WRDN-${b64u(payload)}.${b64u(signature)}`
}

// ── keypair ───────────────────────────────────────────────────────────────────
const vectorsOnly = process.argv.includes('--vectors-only')
const envPath = join(ROOT, '.env.local')
const existing = existsSync(envPath)
  ? readFileSync(envPath, 'utf8').match(/^LICENSE_SIGNING_KEY=(.+)$/m)?.[1]?.trim()
  : null

let seed
if (existing) {
  seed = Buffer.from(existing, 'base64url')
  if (seed.length !== 32) throw new Error(`LICENSE_SIGNING_KEY is ${seed.length} bytes, expected 32`)
  console.log('Reusing the existing signing key from .env.local.')
} else if (vectorsOnly) {
  throw new Error('--vectors-only needs an existing LICENSE_SIGNING_KEY in .env.local')
} else {
  const { privateKey } = generateKeyPairSync('ed25519')
  seed = privateKey.export({ format: 'der', type: 'pkcs8' }).subarray(PKCS8_PREFIX.length)
  appendFileSync(envPath, `${existsSync(envPath) ? '\n' : ''}LICENSE_SIGNING_KEY=${b64u(seed)}\n`)
  console.log('Minted a NEW signing identity and appended it to .env.local.')
  console.log('Put this in the Vercel env as LICENSE_SIGNING_KEY. It is the only copy:')
  console.log(`\n  ${b64u(seed)}\n`)
}

const rawPub = privateToRawPublic(seedToPrivate(seed))

writeFileSync(
  join(ROOT, 'docs/license-pubkey.json'),
  JSON.stringify({ alg: 'ed25519', publicKey: b64u(rawPub) }, null, 2) + '\n',
)

// The Rust side gets the key as a byte array literal so verification needs no
// parsing, no decoding, and no way to fail at runtime on a malformed constant.
const hexBytes = [...rawPub].map((b) => `0x${b.toString(16).padStart(2, '0')}`)
const rows = []
for (let i = 0; i < hexBytes.length; i += 8) rows.push('    ' + hexBytes.slice(i, i + 8).join(', ') + ',')

writeFileSync(
  join(ROOT, 'src-tauri/src/license/pubkey.rs'),
  `// GENERATED by scripts/gen-license-keypair.mjs. Do not edit.\n` +
    `// The public half of the WARDEN license signing identity.\n` +
    `pub const LICENSE_PUBLIC_KEY: [u8; 32] = [\n${rows.join('\n')}\n];\n`,
)

// ── conformance vectors ───────────────────────────────────────────────────────
// Fixed claims and a fixed timestamp, so the file is byte-stable across runs and
// a regeneration shows up as an empty diff unless the format actually moved.
const IAT = 1785700000
const valid = [
  { name: 'single seat', claims: { v: 1, id: 'cs_test_a1', email: 'a@example.com', seats: 1, iat: IAT } },
  { name: 'two seats', claims: { v: 1, id: 'cs_test_b2', email: 'b@example.com', seats: 2, iat: IAT } },
  { name: 'three seats', claims: { v: 1, id: 'cs_test_c3', email: 'c@example.com', seats: 3, iat: IAT } },
  { name: 'plus addressing', claims: { v: 1, id: 'cs_test_d4', email: 'k+warden@example.com', seats: 1, iat: IAT } },
  { name: 'unicode local part', claims: { v: 1, id: 'cs_test_e5', email: 'josé@example.com', seats: 1, iat: IAT } },
]

const vectors = {
  note: 'Shared by the Node signer and the Rust verifier. Both suites read THIS file.',
  publicKey: b64u(rawPub),
  valid: valid.map(({ name, claims }) => ({ name, claims, key: mintKey(seed, claims) })),
  invalid: [],
}

const base = vectors.valid[0].key
const [head, sigPart] = base.split('.')
const payloadB64 = head.slice('WRDN-'.length)
const tamperedPayload = b64u(
  Buffer.from(encodePayload({ ...valid[0].claims, seats: 3 }), 'utf8'),
)
// Flip one bit in the signature rather than replacing it, so the vector proves
// the verifier checks the whole signature and not merely its length.
const sigBytes = Buffer.from(sigPart, 'base64url')
sigBytes[0] ^= 0x01

vectors.invalid = [
  {
    name: 'seats escalated from 1 to 3, signature untouched',
    key: `WRDN-${tamperedPayload}.${sigPart}`,
    reason: 'signature does not cover the modified payload',
  },
  { name: 'one bit flipped in the signature', key: `WRDN-${payloadB64ToKey(payloadB64, sigBytes)}`, reason: 'signature invalid' },
  { name: 'missing WRDN- prefix', key: `${payloadB64}.${sigPart}`, reason: 'malformed' },
]

function payloadB64ToKey(p, sig) {
  return `${p}.${b64u(sig)}`
}

writeFileSync(join(ROOT, 'docs/license-vectors.json'), JSON.stringify(vectors, null, 2) + '\n')

console.log(`Public key: ${b64u(rawPub)}`)
console.log(`Wrote docs/license-pubkey.json, docs/license-vectors.json, src-tauri/src/license/pubkey.rs`)
console.log(`Vectors: ${vectors.valid.length} valid, ${vectors.invalid.length} invalid`)
